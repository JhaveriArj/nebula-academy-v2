/* Generates docs/FTC_MOCK_COVERAGE.md from src/ftc-mock/. CLAUDE.md requires the doc to
   stay current and forbids a lesson calling anything it does not list, so the doc is
   derived rather than maintained. Run: npm run gen:coverage */
import { writeFileSync } from 'node:fs';
import { ALL_NATIVE_CLASSES } from '../src/ftc-mock/registry';
import { STRING_METHODS } from '../src/ftc-mock/javalang';

const byPackage = new Map<string, typeof ALL_NATIVE_CLASSES>();
for (const c of ALL_NATIVE_CLASSES) {
  const pkg = c.fqn.slice(0, c.fqn.lastIndexOf('.'));
  const outer = pkg.replace(/\.[A-Z][A-Za-z0-9_]*$/, '');
  const list = byPackage.get(outer) ?? [];
  list.push(c);
  byPackage.set(outer, list);
}

const lines: string[] = [
  '# Mocked FTC SDK coverage',
  '',
  '**Generated by `npm run gen:coverage`. Do not edit by hand.**',
  '',
  'Every package name and method signature here is the real one, from',
  '[ftc-docs](https://ftc-docs.firstinspires.org) and the',
  '[FtcRobotController](https://github.com/FIRST-Tech-Challenge/FtcRobotController) repo, so a',
  "kid's file pastes into Android Studio unchanged.",
  '',
  '**A lesson may not call anything that is not on this page.** `tests/content.test.ts`',
  'enforces that. If a lesson needs something new, mock it in `src/ftc-mock/` first and',
  'regenerate this page — which also regenerates `ftc-stubs/` for the real-javac gate.',
  '',
  'A method marked **clock** advances the simulation by one 20 ms tick when called. Those are',
  'the methods real FTC code polls in a loop condition, which is how',
  '`while (opModeIsActive())` runs at the right rate. See `docs/ARCHITECTURE.md`.',
  '',
];

const fixedNames = [
  'leftDrive', 'rightDrive', 'frontLeft', 'frontRight', 'backLeft', 'backRight',
  'armMotor', 'clawServo', 'distanceSensor', 'colorSensor', 'imu',
];

lines.push('## Device names', '');
lines.push('Fixed across every tier by CLAUDE.md. `hardwareMap.get` is case-sensitive, exactly as');
lines.push('on a real robot.', '');
lines.push('| Robot | Names |', '|---|---|');
lines.push('| tank (Tiers 0-2) | `leftDrive`, `rightDrive`, `armMotor`, `clawServo`, `distanceSensor`, `colorSensor`, `imu` |');
lines.push('| mecanum (Tiers 3-5) | `frontLeft`, `frontRight`, `backLeft`, `backRight`, `armMotor`, `clawServo`, `distanceSensor`, `colorSensor`, `imu` |');
lines.push('', `All names: ${fixedNames.map((n) => '`' + n + '`').join(', ')}.`, '');

for (const [pkg, classes] of [...byPackage].sort()) {
  lines.push(`## \`${pkg}\``, '');
  for (const c of classes.sort((a, b) => a.simple.localeCompare(b.simple))) {
    const kind = c.kind === 'annotation' ? 'annotation' : c.kind;
    lines.push(`### ${c.simple} <sub>${kind}</sub>`, '');
    if (c.doc) lines.push(c.doc, '');
    if (c.extends) lines.push(`Extends \`${c.extends}\`.`, '');
    if (c.enumConstants?.length) {
      lines.push(`Constants: ${c.enumConstants.map((e) => '`' + e + '`').join(', ')}`, '');
    }
    if (c.annotationElements?.length) {
      lines.push(`Elements: ${c.annotationElements.map((e) => '`' + e + '`').join(', ')}`, '');
    }
    if (c.fields?.length) {
      lines.push('| Field | Type |', '|---|---|');
      for (const f of c.fields) lines.push(`| \`${f.name}\` | \`${f.type}\` |`);
      lines.push('');
    }
    if (c.constructors?.length) {
      for (const k of c.constructors) {
        lines.push(`- \`new ${c.simple.split('.').pop()}(${k.params.join(', ')})\``);
      }
      lines.push('');
    }
    if (c.methods?.length) {
      lines.push('| Method | Returns | |', '|---|---|---|');
      for (const m of c.methods) {
        const params = m.params.map((p, i) => (m.varargs && i === m.params.length - 1 ? `${p}...` : p));
        lines.push(
          `| \`${m.isStatic ? 'static ' : ''}${m.name}(${params.join(', ')})\` | \`${m.returns}\` | ${m.tick ? '**clock**' : ''} |`,
        );
      }
      lines.push('');
    }
  }
}

lines.push('## `java.lang.String` instance methods', '');
lines.push('| Method | Returns |', '|---|---|');
for (const [name, overloads] of Object.entries(STRING_METHODS).sort()) {
  for (const o of overloads) lines.push(`| \`${name}(${o.params.join(', ')})\` | \`${o.returns}\` |`);
}
lines.push('');

lines.push('## Deliberately not mocked', '');
lines.push('Listed so nobody has to guess. A lesson that needs one of these has to be redesigned,');
lines.push('or the feature has to be added to the interpreter first. The browser reports each of');
lines.push('these by name rather than crashing. See `docs/ARCHITECTURE.md`.', '');
for (const item of [
  'Lambdas and method references (`->`, `::`)',
  'try / catch / finally',
  'Collections: `List`, `ArrayList`, `Map`, `HashMap`, and the rest of `java.util`',
  'Generics beyond the `Class<T>` token `hardwareMap.get` needs',
  'Inner, anonymous and local classes (nested `enum` and nested `class` are supported)',
  'Threads, `synchronized`, reflection',
  'File and network I/O',
  'Vuforia, TensorFlow, AprilTag and any season-specific vision library',
  'Records, `var` patterns, sealed types',
]) lines.push(`- ${item}`);
lines.push('');

writeFileSync(new URL('../docs/FTC_MOCK_COVERAGE.md', import.meta.url), lines.join('\n'));
const methodCount = ALL_NATIVE_CLASSES.reduce((n, c) => n + (c.methods?.length ?? 0), 0);
console.log(`gen:coverage  ${ALL_NATIVE_CLASSES.length} classes, ${methodCount} methods -> docs/FTC_MOCK_COVERAGE.md`);
